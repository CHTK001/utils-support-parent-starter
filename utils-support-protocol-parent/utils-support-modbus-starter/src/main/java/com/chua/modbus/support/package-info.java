/**
 * Modbus 客户端与服务端 SPI。
 *
 * <h2>报文结构（Modbus TCP / UDP）</h2>
 * <pre>
 * 00 01 | 00 00 | 00 06 | 01 | 03 | 00 00 | 00 0A
 * 事务号  协议ID   长度    单元  功能码  起始地址   数量
 *  2B     2B      2B      1B     1B      2B       2B
 * └──────── 7 字节 MBAP ────────┘ └──── PDU ────┘
 * </pre>
 *
 * <p>MBAP 固定 7 字节：事务号(2) + 协议标识(2，恒为 0) + 长度(2) + 单元号(1)。
 * 长度字段 = 单元号(1) + PDU 长度；读完 7 字节后还需读取 {@code 长度 - 1} 字节的 PDU。</p>
 *
 * <p>TCP 是字节流，可能粘包/拆包，必须按长度字段缓冲切帧；UDP 一个数据报即一帧，
 * 不需要切流，但同样带 MBAP 长度字段。</p>
 *
 * <h2>串口帧</h2>
 * <ul>
 *   <li>RTU：从站地址(1) + 功能码 + 数据 + CRC16(2)</li>
 *   <li>ASCII：{@code ':'} + 十六进制字符 + LRC + CRLF</li>
 * </ul>
 *
 * <p>PDU 语义（功能码、地址与数量校验、事务号匹配、异常响应 {@code 功能码 | 0x80} + 异常码）
 * 由 j2mod 处理；本模块负责配置、SPI 注册、协议选择与数据区适配。</p>
 *
 * @author CH
 * @since 4.0.0.50
 */
