package com.chua.oracle.support.flyway;

import com.chua.common.support.lang.datasource.flyway.DefaultScriptConverter;
import com.chua.common.support.spi.annotations.Spi;

import java.util.regex.Pattern;

/**
 * Oracle 迁移脚本方言转换器（{@code ScriptConverter} 的 oracle 协议实现）。
 *
 * <p>Oracle 此前没有 ScriptConverter 实现，落到兜底的 {@link DefaultScriptConverter}，
 * 而兜底实现只做了少量类型/函数映射，缺了 Oracle 的硬性约束 —— 迁移脚本在 Oracle 上
 * 基本跑不起来。</p>
 *
 * <p>本类补齐的差异（依据 Oracle 官方文档；标识符定界与自增写法另经
 * H2 的 {@code MODE=Oracle} 兼容模式实测确认）：</p>
 * <ul>
 *   <li><b>标识符定界</b>：Oracle 只认双引号，反引号是语法错。父类的
 *       {@code NO_BACKTICK_PROTOCOLS} 已含本协议，由父类统一改写</li>
 *   <li><b>字符串类型</b>：{@code VARCHAR} 在 Oracle 里是 {@code VARCHAR2} 的别名但已废弃，
 *       统一改写成 {@code VARCHAR2}</li>
 *   <li><b>数值类型</b>：{@code TINYINT}/{@code MEDIUMINT}/{@code INT}/{@code BIGINT}
 *       在 Oracle 里都没有，统一用 {@code NUMBER}；{@code DECIMAL} 是 {@code NUMBER} 的别名</li>
 *   <li><b>布尔类型</b>：Oracle 没有 {@code BOOLEAN} 列类型（PL/SQL 有，SQL 层没有），
 *       改写成 {@code NUMBER(1)}</li>
 *   <li><b>文本类型</b>：{@code TEXT} 家族在 Oracle 里是 {@code CLOB}</li>
 *   <li><b>二进制类型</b>：{@code BLOB}/{@code VARBINARY}/{@code BINARY} → Oracle 的 {@code BLOB}</li>
 *   <li><b>时间类型</b>：{@code DATETIME} → {@code TIMESTAMP}</li>
 *   <li><b>函数</b>：{@code NOW()} → {@code SYSDATE}、{@code IFNULL(a,b)} → {@code NVL(a,b)}</li>
 *   <li><b>列级自增</b>：父类已改写成 {@code GENERATED BY DEFAULT AS IDENTITY}
 *       （Oracle 12c+ 原生支持）</li>
 *   <li><b>{@code INSERT IGNORE}</b>：Oracle 没有「忽略冲突」的修饰写法，整条跳过
 *       （与 Derby / Hive 的处理一致：改写成 {@code MERGE} 需要预知冲突列，
 *       纯文本转换器拿不到元数据）</li>
 *   <li><b>{@code ON DUPLICATE KEY UPDATE}</b>：Oracle 的等价写法是 {@code MERGE INTO ... USING ...}，
 *       需要表结构元数据，整条跳过</li>
 * </ul>
 *
 * <p>扩展方式：扩展键必须等于协议名（{@code @Spi("oracle")} + 本模块
 * {@code META-INF/extensions/...ScriptConverter} 中的 {@code oracle=} 行），
 * 否则会与兜底默认实现同键互相遮蔽。</p>
 *
 * @author CH
 * @since 4.0.0.42
 */
@Spi(value = OracleScriptConverter.PROTOCOL, order = 100)
public class OracleScriptConverter extends DefaultScriptConverter {

    /**
     * 本协议名（同时作为 SPI 扩展键）
     */
    public static final String PROTOCOL = "oracle";

    /**
     * {@code INSERT IGNORE INTO} — 整条跳过
     */
    private static final Pattern INSERT_IGNORE = Pattern.compile(
            "(?i)^\\s*INSERT\\s+IGNORE\\b");

    /**
     * {@code ON DUPLICATE KEY UPDATE} — 整条跳过
     */
    private static final Pattern ON_DUPLICATE_KEY_UPDATE = Pattern.compile(
            "(?i)\\bON\\s+DUPLICATE\\s+KEY\\s+UPDATE\\b");

    /**
     * {@code VARCHAR} → {@code VARCHAR2}。
     *
     * <p>Oracle 里 {@code VARCHAR} 是 {@code VARCHAR2} 的同义词，但官方已标注为
     * 不推荐使用，统一改写避免告警。</p>
     */
    private static final Pattern VARCHAR_TYPE = Pattern.compile("(?i)\\bVARCHAR\\b(?!2)");

    /**
     * MySQL 的整型族 → Oracle 的 {@code NUMBER}。
     *
     * <p>Oracle 没有 {@code TINYINT}/{@code MEDIUMINT}/{@code INT}/{@code INTEGER}/{@code BIGINT}
     * 这些类型名，数值统一用 {@code NUMBER}（不带长度精度时等价于最大精度）。</p>
     *
     * <p>{@code SMALLINT} 保留：Oracle 确实有 {@code SMALLINT}（{@code NUMBER(5)} 的同义词）。</p>
     */
    private static final Pattern INTEGER_TYPE = Pattern.compile(
            "(?i)\\b(?:TINYINT|MEDIUMINT|INT|INTEGER|BIGINT)\\b");

    /**
     * {@code BOOLEAN} / {@code BOOL} → Oracle 的 {@code NUMBER(1)}。
     *
     * <p>Oracle 的 SQL 层没有布尔列类型（只有 PL/SQL 里的 BOOLEAN），
     * 布尔列用 {@code NUMBER(1)} 存 0/1。</p>
     */
    private static final Pattern BOOLEAN_TYPE = Pattern.compile("(?i)\\bBOOLEAN\\b|\\bBOOL\\b");

    /**
     * {@code YEAR} → Oracle 的 {@code NUMBER(4)}。
     *
     * <p>Oracle 没有 {@code YEAR} 类型。</p>
     */
    private static final Pattern YEAR_TYPE = Pattern.compile("(?i)\\bYEAR\\b");

    /**
     * {@code DOUBLE} / {@code FLOAT} → Oracle 的 {@code BINARY_DOUBLE}。
     *
     * <p>Oracle 没有 {@code DOUBLE} 这个类型名。浮点双精度的标准写法是
     * {@code BINARY_DOUBLE}（IEEE 754 双精度），{@code BINARY_FLOAT} 是单精度。</p>
     */
    private static final Pattern DOUBLE_TYPE = Pattern.compile(
            "(?i)\\bDOUBLE\\b(?!\\s+PRECISION)|\\bFLOAT\\b");

    /**
     * {@code BLOB} / {@code VARBINARY(n)} / {@code BINARY(n)} → Oracle 的 {@code BLOB}。
     */
    private static final Pattern BINARY_TYPE = Pattern.compile(
            "(?i)\\b(?:VAR)?BINARY\\s*\\(\\s*\\d+\\s*\\)|\\bBLOB\\b");

    @Override
    public boolean supports(String protocol) {
        return PROTOCOL.equalsIgnoreCase(protocol);
    }

    @Override
    public String convert(String statement, String protocol) {
        // 先走父类：剥离表尾 MySQL 属性、行内 KEY/UNIQUE KEY、列内联 COMMENT、列级 CHARSET/COLLATE、
        // 标识符定界改写（Oracle 只认双引号），以及 TEXT/CLOB/DATETIME/NOW()/IFNULL() 的基础映射
        String converted = super.convert(statement, protocol);
        if (converted == null || converted.isBlank()) {
            return converted;
        }
        // Oracle 没有「忽略冲突」与 upsert 的 MySQL 语法，整条跳过
        if (INSERT_IGNORE.matcher(converted).find()) {
            return null;
        }
        if (ON_DUPLICATE_KEY_UPDATE.matcher(converted).find()) {
            return null;
        }
        // 类型映射
        converted = VARCHAR_TYPE.matcher(converted).replaceAll("VARCHAR2");
        converted = INTEGER_TYPE.matcher(converted).replaceAll("NUMBER");
        converted = BOOLEAN_TYPE.matcher(converted).replaceAll("NUMBER(1)");
        converted = YEAR_TYPE.matcher(converted).replaceAll("NUMBER(4)");
        converted = DOUBLE_TYPE.matcher(converted).replaceAll("BINARY_DOUBLE");
        converted = BINARY_TYPE.matcher(converted).replaceAll("BLOB");
        return converted;
    }
}
