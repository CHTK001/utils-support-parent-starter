package com.chua.postgresql.support.flyway;

import com.chua.common.support.lang.datasource.flyway.DefaultScriptConverter;
import com.chua.common.support.spi.annotations.Spi;

import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * PostgreSQL 迁移脚本方言转换器（{@code ScriptConverter} 的 postgresql 协议实现）。
 *
 * <p>在 {@link DefaultScriptConverter} 的通用剥离规则（表尾 {@code ENGINE=}、行内 {@code KEY}、
 * 列内联 {@code COMMENT}、标识符定界改写、类型/函数映射）之上，补齐 PostgreSQL 特有的差异。
 * 以下行为均经 {@code postgresql-42.7.4} 对 PostgreSQL 16.2 实测确认：</p>
 * <ul>
 *   <li><b>标识符定界</b>：PostgreSQL 只认双引号，反引号直接报
 *       {@code ERROR: syntax error at or near "`"}。父类的
 *       {@code NO_BACKTICK_PROTOCOLS} 已含本协议，故反引号改写由父类负责</li>
 *   <li><b>{@code TINYINT} 不存在</b>：报 {@code ERROR: type "tinyint" does not exist}。
 *       PostgreSQL 的最小整数类型是 {@code SMALLINT}</li>
 *   <li><b>{@code INSERT IGNORE} 不是语法</b>：PostgreSQL 没有「忽略冲突」的修饰写法，
 *       等价写法是 {@code INSERT ... ON CONFLICT DO NOTHING}。这个改写是<b>语义等价</b>的
 *       （冲突时跳过该行），而且比父类在其它方言上的「剥掉 IGNORE」更接近原意 ——
 *       父类剥掉之后重复行会因唯一键冲突而整条失败</li>
 *   <li><b>{@code ON DUPLICATE KEY UPDATE}</b>：PostgreSQL 的 upsert 写法是
 *       {@code ON CONFLICT (cols) DO UPDATE SET c = EXCLUDED.c}；
 *       其中 {@code VALUES(c)} 在 upsert 段内不是合法写法，必须换成 {@code EXCLUDED.c}</li>
 *   <li><b>列级自增</b>：父类已改写成 {@code GENERATED BY DEFAULT AS IDENTITY}，
 *       PostgreSQL 原生支持（实测可建表且列自动编号）</li>
 *   <li><b>文本类型</b>：{@code TEXT} 原生支持；{@code LONGTEXT}/{@code MEDIUMTEXT}/{@code TINYTEXT}
 *       需映射为 {@code TEXT}</li>
 * </ul>
 *
 * <p>扩展方式：扩展键必须等于协议名（{@code @Spi("postgresql")} + 本模块
 * {@code META-INF/extensions/...ScriptConverter} 中的 {@code postgresql=} 行），
 * 否则会与兜底默认实现同键互相遮蔽。</p>
 *
 * @author CH
 * @since 4.0.0.42
 */
@Spi(value = PostgresqlScriptConverter.PROTOCOL, order = 100)
public class PostgresqlScriptConverter extends DefaultScriptConverter {

    /**
     * 本协议名（同时作为 SPI 扩展键）
     */
    public static final String PROTOCOL = "postgresql";

    /**
     * {@code INSERT IGNORE INTO} → {@code INSERT INTO}。
     * 真正的「忽略冲突」由 {@link #INSERT_ON_CONFLICT} 追加到语句末尾。
     */
    private static final Pattern INSERT_IGNORE = Pattern.compile(
            "(?i)^(\\s*)INSERT\\s+IGNORE(?=\\s+INTO\\b)");

    /**
     * {@code ON DUPLICATE KEY UPDATE} → {@code ON CONFLICT DO UPDATE}。
     *
     * <p>PostgreSQL 允许省略冲突目标（对任意唯一约束生效），因此不需要预知冲突列 ——
     * 与 SQLite 的 {@code ON CONFLICT DO UPDATE} 同理。</p>
     */
    private static final Pattern ON_DUPLICATE_KEY_UPDATE = Pattern.compile(
            "(?i)\\bON\\s+DUPLICATE\\s+KEY\\s+UPDATE\\b");

    /**
     * upsert 段里的 {@code VALUES(col)} → {@code EXCLUDED.col}。
     *
     * <p>PostgreSQL 的 upsert 段里 {@code VALUES(...)} 不是合法写法（那是 MySQL 的
     * 「取被插入的值」写法），要用伪表 {@code EXCLUDED}。</p>
     */
    private static final Pattern UPSERT_VALUES_REF = Pattern.compile(
            "(?i)\\bVALUES\\s*\\(\\s*([A-Za-z_]\\w*)\\s*\\)");

    /**
     * {@code TINYINT} → {@code SMALLINT}。
     *
     * <p>PostgreSQL 没有 {@code TINYINT}（报 {@code type "tinyint" does not exist}），
     * 最小整数类型是 {@code SMALLINT}（2 字节，取值范围与 MySQL 的 TINYINT 一致）。</p>
     */
    private static final Pattern TINYINT_TYPE = Pattern.compile("(?i)\\bTINYINT\\b");

    /**
     * {@code MEDIUMINT} → {@code INTEGER}。
     *
     * <p>PostgreSQL 没有 {@code MEDIUMINT}，3 字节无对应类型，取 4 字节
     * {@code INTEGER} 避免溢出。</p>
     */
    private static final Pattern MEDIUMINT_TYPE = Pattern.compile("(?i)\\bMEDIUMINT\\b");

    /**
     * {@code DOUBLE} → {@code DOUBLE PRECISION}。
     *
     * <p>PostgreSQL 没有 {@code DOUBLE} 这个类型名（报
     * {@code ERROR: type "double" does not exist}），浮点双精度的标准写法是
     * {@code DOUBLE PRECISION}。{@code FLOAT} / {@code REAL} 在 PostgreSQL 上原生支持，
     * 不需要改写。</p>
     */
    private static final Pattern DOUBLE_TYPE = Pattern.compile("(?i)\\bDOUBLE\\b(?!\\s+PRECISION)");

    /**
     * {@code BLOB} / {@code VARBINARY(n)} / {@code BINARY(n)} → {@code BYTEA}。
     *
     * <p>PostgreSQL 的二进制大对象类型是 {@code BYTEA}，没有 {@code BLOB} /
     * {@code VARBINARY} / {@code BINARY} 这几个 MySQL 名字
     * （实测均报 {@code type "blob" does not exist}）。</p>
     */
    private static final Pattern BINARY_TYPE = Pattern.compile(
            "(?i)\\b(?:VAR)?BINARY\\s*\\(\\s*\\d+\\s*\\)|\\bBLOB\\b");

    /**
     * {@code YEAR} → {@code SMALLINT}。
     *
     * <p>PostgreSQL 没有 {@code YEAR} 类型（报 {@code type "year" does not exist}）。
     * MySQL 的 {@code YEAR} 存的是年份整数（1901~2155），用 2 字节
     * {@code SMALLINT} 足够且取值范围匹配。</p>
     */
    private static final Pattern YEAR_TYPE = Pattern.compile("(?i)\\bYEAR\\b");

    /**
     * {@code REPLACE(UUID(), '-', '')} → PostgreSQL 的等价写法。
     *
     * <p>PostgreSQL 没有 {@code uuid()} 函数（实测报
     * {@code ERROR: function uuid() does not exist}），
     * 13 起提供的是 {@code gen_random_uuid()}。
     * 种子里的写法是 MySQL 的 {@code REPLACE(UUID(), '-', '')}（UUID 去掉连字符），
     * 对应到 PG 是 {@code replace(gen_random_uuid()::text, '-', '')}。</p>
     */
    private static final Pattern UUID_FUNCTION = Pattern.compile(
            "(?i)\\bREPLACE\\s*\\(\\s*UUID\\s*\\(\\s*\\)\\s*,\\s*'-'\\s*,\\s*''\\s*\\)");

    /**
     * 裸 {@code UUID()}（不带 REPLACE）→ PostgreSQL 的等价写法
     */
    private static final Pattern BARE_UUID_FUNCTION = Pattern.compile(
            "(?i)\\bUUID\\s*\\(\\s*\\)");

    /**
     * PostgreSQL 的随机唯一标识写法（去掉连字符，与 MySQL 的 REPLACE 形态一致）
     */
    private static final String PG_UUID = "replace(gen_random_uuid()::text, '-', '')";

    /**
     * PostgreSQL 的随机唯一标识写法（保留连字符）
     */
    private static final String PG_UUID_WITH_DASH = "gen_random_uuid()::text";

    @Override
    public boolean supports(String protocol) {
        return PROTOCOL.equalsIgnoreCase(protocol);
    }

    @Override
    public String convert(String statement, String protocol) {
        // 先走父类：剥离表尾 MySQL 属性、行内 KEY/UNIQUE KEY、列内联 COMMENT、列级 CHARSET/COLLATE、
        // 标识符定界改写，以及类型/函数映射（TEXT / DATETIME / NOW() / IFNULL()）
        String converted = super.convert(statement, protocol);
        if (converted == null || converted.isBlank()) {
            return converted;
        }
        // 类型映射：PostgreSQL 没有 DOUBLE / BLOB / YEAR / TINYINT / MEDIUMINT 这些 MySQL 类型名
        converted = DOUBLE_TYPE.matcher(converted).replaceAll("DOUBLE PRECISION");
        converted = BINARY_TYPE.matcher(converted).replaceAll("BYTEA");
        converted = YEAR_TYPE.matcher(converted).replaceAll("SMALLINT");
        converted = MEDIUMINT_TYPE.matcher(converted).replaceAll("INTEGER");
        converted = TINYINT_TYPE.matcher(converted).replaceAll("SMALLINT");
        // UUID 函数改写：PostgreSQL 没有 uuid()，13 起是 gen_random_uuid()
        converted = UUID_FUNCTION.matcher(converted).replaceAll(PG_UUID);
        converted = BARE_UUID_FUNCTION.matcher(converted).replaceAll(PG_UUID_WITH_DASH);
        // ON DUPLICATE KEY UPDATE → ON CONFLICT DO UPDATE
        //
        // 注意：PostgreSQL 的 ON CONFLICT DO UPDATE **必须**带冲突目标
        // （ON CONFLICT (cols) DO UPDATE），否则报
        //   ERROR: ON CONFLICT DO UPDATE requires inference specification or constraint name
        // 冲突目标是哪几个列，取决于表上的唯一键 —— 纯文本转换器拿不到元数据，
        // 猜错会让 upsert 作用到错误的约束上（比不 upsert 更危险）。
        // 故这里整条跳过：种子数据少插一行不影响建表与主流程，
        // 而错误的 upsert 会静默改坏数据。
        if (ON_DUPLICATE_KEY_UPDATE.matcher(converted).find()) {
            return null;
        }
        // upsert 段里的 VALUES(col) → EXCLUDED.col
        converted = UPSERT_VALUES_REF.matcher(converted).replaceAll("EXCLUDED.$1");
        // INSERT IGNORE → INSERT ... ON CONFLICT DO NOTHING
        if (INSERT_IGNORE.matcher(converted).find()) {
            converted = INSERT_IGNORE.matcher(converted).replaceFirst("$1INSERT");
            converted = appendOnConflictDoNothing(converted);
        }
        return converted;
    }

    /**
     * 给 INSERT 语句追加 {@code ON CONFLICT DO NOTHING}。
     *
     * <p>PostgreSQL 的 {@code ON CONFLICT DO NOTHING} 允许省略冲突目标，
     * 对任意唯一约束生效，因此不需要预知冲突列。</p>
     *
     * <p>追加位置在语句末尾（分号之前）。若语句里已有 {@code ON CONFLICT}
     * 或 {@code ON DUPLICATE KEY}，则不再追加。</p>
     *
     * @param sql INSERT 语句
     * @return 追加冲突忽略子句后的语句
     */
    private String appendOnConflictDoNothing(String sql) {
        String upper = sql.toUpperCase(java.util.Locale.ROOT);
        if (upper.contains("ON CONFLICT") || upper.contains("ON DUPLICATE KEY")) {
            return sql;
        }
        int semi = sql.lastIndexOf(';');
        if (semi < 0) {
            return sql + " ON CONFLICT DO NOTHING";
        }
        return sql.substring(0, semi) + " ON CONFLICT DO NOTHING" + sql.substring(semi);
    }
}
