package com.chua.common.support.constant;

import java.util.regex.Pattern;

/**
 * 正则表达式常量接口，集中定义项目中使用的各类校验正则表达式。
 *
 * <p>该接口包含以下类别的正则常量：
 * <ul>
 *   <li><b>联系方式</b> — 手机号（大陆/香港/澳门/台湾）、邮箱、固话、400/800 电话</li>
 *   <li><b>身份标识</b> — 身份证号、统一社会信用代码、车辆 VIN、驾驶证档案编号</li>
 *   <li><b>网络地址</b> — IPv4、IPv6、URL、URI、MAC 地址</li>
 *   <li><b>文本格式</b> — 通用标识符、数字、字母、中文、金额、时间、生日</li>
 *   <li><b>编码相关</b> — UUID（标准/简化）、十六进制、JAR 路径、控制字符</li>
 *   <li><b>URL 处理</b> — URI 协议方案校验、多余路径段清除</li>
 *   <li><b>邮政编码</b> — 中国 6 位邮编</li>
 * </ul>
 *
 * @author CH
 * @since 2024-01-01
 */
@SuppressWarnings("all")
public interface RegexConstant {

    // ========================== 联系方式 ==========================

    /**
     * 电子邮箱正则表达式。
     * 基于 RFC 5322 规范（参考 http://emailregex.com/）。
     * 支持标准邮箱格式、引号字符串格式、IP 字面量域名。
     */
    String EMAIL = "(?:[a-z0-9!#$%&'*+/=?^_`{|}~-]+(?:\\.[a-z0-9!#$%&'*+/=?^_`{|}~-]+)*|\"(?:[\\x01-\\x08\\x0b\\x0c\\x0e-\\x1f\\x21\\x23-\\x5b\\x5d-\\x7f]|\\\\[\\x01-\\x09\\x0b\\x0c\\x0e-\\x7f])*\")@(?:(?:[a-z0-9](?:[a-z0-9-]*[a-z0-9])?\\.)+[a-z0-9](?:[a-z0-9-]*[a-z0-9])?|\\[(?:(?:25[0-5]|2[0-4][0-9]|[01]?[0-9][0-9]?)\\.){3}(?:25[0-5]|2[0-4][0-9]|[01]?[0-9][0-9]?|[a-z0-9-]*[a-z0-9]:(?:[\\x01-\\x08\\x0b\\x0c\\x0e-\\x1f\\x21-\\x5a\\x53-\\x7f]|\\\\[\\x01-\\x09\\x0b\\x0c\\x0e-\\x7f])+)])";

    /**
     * 中国大陆手机号正则表达式。
     * 匹配以 1 开头、第二位为 3-9 的 11 位号码（可选 +86/086/0 前缀）。
     */
    String MOBILE = "(?:0|86|\\+86)?1[3-9]\\d{9}";

    /**
     * 中国香港手机号正则表达式。
     * 8 位数字，可选 +852/852/0 前缀。
     */
    String MOBILE_HK = "(?:0|852|\\+852)?\\d{8}";

    /**
     * 中国台湾手机号正则表达式。
     * 10 位数字（09 开头 + 8 位），可选 +886/886/0 前缀。
     */
    String MOBILE_TW = "(?:0|886|\\+886)?(?:|-)09\\d{8}";

    /**
     * 中国澳门手机号正则表达式。
     * 8 位数字（6 开头 + 7 位），可选 +853/853/0 前缀。
     */
    String MOBILE_MO = "(?:0|853|\\+853)?(?:|-)6\\d{7}";

    /**
     * 中国大陆固定电话正则表达式。
     * 支持区号（3-4 位）+ 号码（6-8 位），区号可选短横线分隔。
     */
    String TEL = "(010|02\\d|0[3-9]\\d{2})-?(\\d{6,8})";

    /**
     * 400/800 企业服务热线正则表达式。
     * 支持 400/800 开头的 10 位号码及普通长途电话。
     */
    String TEL_400_800 = "0\\d{2,3}[\\- ]?[1-9]\\d{6,7}|[48]00[\\- ]?[1-9]\\d{6}";

    // ========================== 身份标识 ==========================

    /**
     * 18 位公民身份证号正则表达式。
     * 支持数字和末位 X/x，按 GB 11643 标准。
     */
    String CITIZEN_ID = "[1-9]\\d{5}[1-2]\\d{3}((0\\d)|(1[0-2]))(([012]\\d)|3[0-1])\\d{3}(\\d|X|x)";

    /**
     * 统一社会信用代码正则表达式。
     * 18 位（2 位字母数字 + 6 位数字 + 10 位字母数字），不含 I/O/Q/S/V/Z。
     */
    String CREDIT_CODE = "^[0-9A-HJ-NPQRTUWXY]{2}\\d{6}[0-9A-HJ-NPQRTUWXY]{10}$";

    /**
     * 车辆识别代号（VIN）正则表达式。
     * 17 位字母数字（不含 I、O、Q）。
     */
    String CAR_VIN = "^[A-Za-z0-9]{17}$";

    /**
     * 驾驶证档案编号正则表达式。
     * 12 位数字。
     */
    String CAR_DRIVING_LICENCE = "^[0-9]{12}$";

    // ========================== 网络地址 ==========================

    /**
     * IPv4 地址正则表达式。
     * 严格校验 4 段 0-255，点分十进制格式。
     */
    String IPV4 = "^(25[0-5]|2[0-4]\\d|[0-1]?\\d?\\d)\\.(25[0-5]|2[0-4]\\d|[0-1]?\\d?\\d)\\.(25[0-5]|2[0-4]\\d|[0-1]?\\d?\\d)\\.(25[0-5]|2[0-4]\\d|[0-1]?\\d?\\d)$";

    /**
     * IPv6 地址正则表达式。
     * 支持完整格式、压缩格式、IPv4 映射地址、链路本地地址。
     */
    String IPV6 = "(([0-9a-fA-F]{1,4}:){7}[0-9a-fA-F]{1,4}|([0-9a-fA-F]{1,4}:){1,7}:|([0-9a-fA-F]{1,4}:){1,6}:[0-9a-fA-F]{1,4}|([0-9a-fA-F]{1,4}:){1,5}(:[0-9a-fA-F]{1,4}){1,2}|([0-9a-fA-F]{1,4}:){1,4}(:[0-9a-fA-F]{1,4}){1,3}|([0-9a-fA-F]{1,4}:){1,3}(:[0-9a-fA-F]{1,4}){1,4}|([0-9a-fA-F]{1,4}:){1,2}(:[0-9a-fA-F]{1,4}){1,5}|[0-9a-fA-F]{1,4}:((:[0-9a-fA-F]{1,4}){1,6})|:((:[0-9a-fA-F]{1,4}){1,7}|:)|fe80:(:[0-9a-fA-F]{0,4}){0,4}%[0-9a-zA-Z]+|::(ffff(:0{1,4})?:)?((25[0-5]|(2[0-4]|1?[0-9])?[0-9])\\.){3}(25[0-5]|(2[0-4]|1?[0-9])?[0-9])|([0-9a-fA-F]{1,4}:){1,4}:((25[0-5]|(2[0-4]|1?[0-9])?[0-9])\\.){3}(25[0-5]|(2[0-4]|1?[0-9])?[0-9]))";

    /**
     * IPv4 地址匹配正则（预编译 Pattern）。
     */
    Pattern ADDRESS = Pattern.compile(
            "([1-9]|[1-9]\\\\d|1\\\\d{2}|2[0-4]\\\\d|25[0-5])(\\\\.(\\\\d|[1-9]\\\\d|1\\\\d{2}|2[0-4]\\\\d|25[0-5])){3}");

    /**
     * URI 正则表达式（参考 RFC 3986 Appendix B）。
     * 分解协议、主机、路径、查询、片段。
     */
    String URI = "^(([^:/?#]+):)?(//([^/?#]*))?([^?#]*)(\\?([^#]*))?(#(.*))?";

    /**
     * URL 正则表达式。
     * 匹配常见协议（http/https/ftp/file 等）的 URL。
     */
    String URL = "[a-zA-Z]+://[\\w-+&@#/%?=~_|!:,.;]*[\\w-+&@#/%=~_|]";

    /**
     * HTTP URL 正则表达式。
     * 仅匹配 http/https/ftp/file 协议的 URL。
     */
    String URL_HTTP = "(https?|ftp|file)://[\\w-+&@#/%?=~_|!:,.;]*[\\w-+&@#/%=~_|]";

    /**
     * MAC 地址正则表达式。
     * 支持冒号或短横线分隔的 6 组十六进制数，或 0x 前缀格式。
     */
    String MAC_ADDRESS = "((?:[a-fA-F0-9]{1,2}[:-]){5}[a-fA-F0-9]{1,2})|0x(\\d{12}).+ETHER";

    // ========================== 文本格式 ==========================

    /**
     * 通用标识符正则。
     * 匹配字母、数字、下划线组成的字符串（不含中文）。
     */
    String GENERAL = "^\\w+$";

    /**
     * 含中文的通用标识符正则。
     * 允许字母、数字、下划线和中文汉字。
     */
    String GENERAL_WITH_CHINESE = "^[\u4E00-\u9FFF\\w]+$";

    /**
     * 纯数字正则。
     * 匹配一个或多个数字字符。
     */
    String NUMBERS = "\\d+";

    /**
     * 纯字母正则。
     * 匹配一个或多个大小写英文字母。
     */
    String WORD = "[a-zA-Z]+";

    /**
     * 单个中文字符正则。
     * 匹配 Unicode CJK 统一表意文字（\u4e00-\u9fa5）。
     */
    String CHINESE_V2 = "[\\u4e00-\\u9fa5]";

    /**
     * 中文字符串正则。
     * 匹配一个或多个中文字符。
     */
    String CHINESES = CHINESE_V2 + "+";

    /**
     * 金额正则。
     * 匹配正数金额，支持可选小数部分。
     */
    String MONEY = "^(\\d+(?:\\.\\d+)?)$";

    /**
     * 时间格式正则。
     * 匹配 HH:mm 或 HH:mm:ss。
     */
    String TIME = "\\d{1,2}:\\d{1,2}(:\\d{1,2})?";

    /**
     * 生日日期正则。
     * 支持年-月-日、年/月/日、年.月.日 及空格分隔。
     */
    String BIRTHDAY = "^(\\d{2,4})([/\\-.   ]?)(\\d{1,2})([/\\-.   ]?)(\\d{1,2})   ?$";

    /**
     * 正则分组反向引用表达式。
     * 匹配形如 $1、$12 的反向引用。
     */
    String GROUP_VAR = "\\$(\\d+)";

    /**
     * 空白字符匹配正则（预编译 Pattern）。
     * 匹配一个或多个空白字符（空格、制表符、换行等）。
     */
    Pattern PATTERN_EMPTY = Pattern.compile("\\s+");

    /**
     * 十进制数字匹配正则（预编译 Pattern）。
     * 支持整数、浮点数（含 f/d 后缀）、科学计数法。
     */
    Pattern DECIMALS = Pattern.compile(
            "(-?\\d*([fdFD])*)|(-?\\d*\\.\\d*([fdFD])*)|(-?\\d*\\.\\d*e\\d*)|(-?\\d*e\\d*)");

    /**
     * 日期格式匹配正则（预编译 Pattern）。
     * 匹配 yyyy-MM-dd、yyyy/MM/dd、yyyy.MM.dd 格式。
     */
    Pattern DATE = Pattern.compile("[1-9]{4}([-./])\\d{1,2}\\1\\d{1,2}");

    /**
     * 字符串切割正则。
     * 按逗号或分号分割。
     */
    String CUT = "[,;]{1}";

    // ========================== 编码相关 ==========================

    /**
     * UUID 标准格式正则。
     * 匹配带连字符的 36 位 UUID（8-4-4-4-12）。
     */
    String UUID_REGEX = "^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$";

    /**
     * UUID 简化格式正则。
     * 匹配不带连字符的 32 位十六进制字符串。
     */
    String UUID_SIMPLE = "^[0-9a-fA-F]{32}$";

    /**
     * 十六进制字符串正则。
     * 匹配仅含数字和字母 A-F/a-f 的字符串。
     */
    String HEX = "^[a-fA-F0-9]+$";

    /**
     * JAR 文件路径匹配正则。
     * 判断路径是否指向 JAR 文件及其内部资源。
     */
    String JAR_PATTERN = ".*\\.jar(\\!.*|$)";

    // ========================== 编码相关（补充） ==========================

    /**
     * ASCII 控制字符匹配正则（预编译 Pattern）。
     * 匹配 0x00-0x1F 和 0x7F（DEL）范围内的控制字符。
     */
    Pattern CONTROL_CHARS = Pattern.compile("[\\x00-\\x1f\\x7f]");

    /**
     * URI 协议方案匹配正则（预编译 Pattern）。
     * 匹配以字母开头、后跟字母/数字/+/-/. 的 URI scheme（如 http://、ftp://）。
     */
    Pattern VALID_URI_SCHEME = Pattern.compile("^[a-zA-Z][a-zA-Z0-9+.-]*://");

    /**
     * URL 多余路径段匹配正则（预编译 Pattern）。
     * 匹配单点段（/./）和双点段（/../），用于规范化 URL 路径。
     */
    Pattern EXTRA_DOT_SEGMENTS_PATTERN = Pattern.compile("(?<=/)\\.(?=/|$)|(?<=/)\\.\\.(?=/|$)");

    /**
     * 整数匹配正则（预编译 Pattern）。
     * 匹配可选负号开头、首位 1-9 的纯数字整数。
     */
    Pattern INT_PATTERN = Pattern.compile("-?[1-9]\\d*");

    // ========================== 邮政编码 ==========================

    /**
     * 中国邮政编码正则表达式。
     * 匹配 6 位邮编（含港澳台部分区域）。
     */
    String ZIP_CODE = "^(0[1-7]|1[0-356]|2[0-7]|3[0-6]|4[0-7]|5[0-7]|6[0-7]|7[0-5]|8[0-9]|9[0-8])\\d{4}|99907[78]$";


}
