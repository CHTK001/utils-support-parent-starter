import com.chua.common.support.lang.datasource.engine.Engine;
import com.chua.oracle.support.engine.OracleEngine;

import java.net.InetSocketAddress;
import java.net.Socket;
import java.util.List;
import java.util.Map;

/**
 * 引擎验收运行器 —— 阶段二十四：Oracle 真实实例读写与 Oracle SQL 语义。
 *
 * <p>本机没有容器运行时（`docker` / `podman` / `nerdctl` / `wsl` 均不存在），
 * 因此本阶段使用 <b>Oracle Database 21c Express Edition（Windows 原生安装）</b>：
 * 官方 XE 安装包（`OracleXE213_Win64.zip`）静默安装，实例 `XE`，监听
 * `127.0.0.1:1521`，业务库为可插拔库 `XEPDB1`。</p>
 *
 * <p>覆盖内容：DDL/DML、`ROWNUM` 分页真实边界、类型映射、Unicode 往返、
 * Oracle 专有语义（`product_component_version`、`dual`、`LENGTH` 按字符计数、
 * <b>空串即 NULL</b>、`DATE` 算术、`GENERATED BY DEFAULT AS IDENTITY`、
 * `TIMESTAMP DEFAULT SYSTIMESTAMP`）、`ORA-00942` / `ORA-00001` 失败语义。</p>
 *
 * <p><b>跳过语义</b>：实例不可达时打印 {@code [SKIP]} 与 {@code STAGE24_SKIP=1}
 * 并以退出码 0 结束——其他机器不装 Oracle 也能跑完整个套件；
 * 日志里能看到 SKIP 标记，不会被误当成「已通过」。</p>
 */
public final class EngineOracle {

    /** 实例地址：默认本机 1521（可用环境变量覆盖）。 */
    private static final String HOST = env("ORACLE_HOST", "127.0.0.1");
    private static final int PORT = Integer.parseInt(env("ORACLE_PORT", "1521"));
    private static final String DATABASE = env("ORACLE_DB", "XEPDB1");
    /** DBA 账号（XE 安装时由 response file 设定），仅用于建验收用户。 */
    private static final String SYS_USER = env("ORACLE_SYS_USER", "system");
    private static final String SYS_PASSWORD = env("ORACLE_SYS_PASSWORD", "Oracle#2026");
    /** 验收用户（最小权限：CONNECT / RESOURCE / UNLIMITED TABLESPACE）。 */
    private static final String APP_USER = env("ORACLE_USER", "engine_accept");
    private static final String APP_PASSWORD = env("ORACLE_PASSWORD", "Engine#2026");

    private EngineOracle() {
    }

    public static void main(String[] args) {
        EngineFunctional.emit("=".repeat(78));
        EngineFunctional.emit("  引擎验收 阶段二十四：Oracle 真实实例（" + HOST + ":" + PORT + "/" + DATABASE + "）");
        EngineFunctional.emit("=".repeat(78));

        if (!reachable()) {
            EngineFunctional.emit("[SKIP] 未检测到 Oracle 监听 " + HOST + ":" + PORT
                    + "（本阶段需要先安装并启动 Oracle XE）");
            EngineFunctional.emit("STAGE24_SKIP=1");
            EngineFunctional.emit("  结果: PASS=0  FAIL=0  SKIP=1");
            EngineFunctional.emit("=".repeat(78));
            System.exit(0);
        }

        OracleEngine engine = (OracleEngine) Engine.create("oracle");
        try {
            // 1. 先用 DBA 账号把验收用户准备好（幂等：已存在则忽略 ORA-01920）。
            engine.addDataSource("dba", HOST, PORT, DATABASE, SYS_USER, SYS_PASSWORD);
            engine.executeSql("BEGIN EXECUTE IMMEDIATE 'CREATE USER " + APP_USER
                    + " IDENTIFIED BY \"" + APP_PASSWORD + "\"'; EXCEPTION WHEN OTHERS THEN"
                    + " IF SQLCODE != -1920 THEN RAISE; END IF; END;");
            engine.executeSql("GRANT CONNECT, RESOURCE, UNLIMITED TABLESPACE TO " + APP_USER);

            // 2. 切到最小权限的验收用户。
            engine.addDataSource("default", HOST, PORT, DATABASE, APP_USER, APP_PASSWORD);
            engine.setDefaultDataSourceName("default");
            engine.queryValue("SELECT 1 FROM dual");
        } catch (RuntimeException e) {
            EngineFunctional.recordFail("oracle 初始化失败: " + e);
            EngineFunctional.finishAndExit("EngineOracle-report.txt");
            return;
        }

        // 3. Oracle 专有语义。必须在通用套件之前：sqlSuite 结束时会 close() 引擎。
        oracleSemantics(engine);

        // 4. 复用通用 JDBC 套件（建表/插入/查询/分页/count/Lambda/batch/守卫/非法入参）。
        //    Oracle 不支持 DROP TABLE IF EXISTS，故先把可能的残留表清掉。
        dropAll(engine);
        EngineFunctional.sqlSuite("oracle", () -> engine, EngineFunctional.Profile.JDBC);

        // 5. 关闭后的错误语义。
        EngineFunctional.check("oracle.关闭后调用：报「引擎已关闭」而不是「不支持 SQL」", () -> {
            try {
                engine.querySql("SELECT 1 FROM dual");
                throw new EngineFunctional.HarnessFailure("close() 后仍可查询");
            } catch (EngineFunctional.HarnessFailure f) {
                throw f;
            } catch (RuntimeException expected) {
                String msg = String.valueOf(expected.getMessage());
                if (!msg.contains("已关闭")) {
                    throw new EngineFunctional.HarnessFailure("消息未指明已关闭: " + msg);
                }
                if (msg.contains("不支持")) {
                    throw new EngineFunctional.HarnessFailure("关闭后仍说「不支持」: " + msg);
                }
                return expected.getClass().getSimpleName() + ": " + msg;
            }
        });

        EngineFunctional.finishAndExit("EngineOracle-report.txt");
    }

    // ==================== Oracle 专有语义 ====================

    private static void oracleSemantics(Engine e) {
        EngineFunctional.emit("--- oracle.semantics ---");

        EngineFunctional.check("oracle.服务端版本确实是 Oracle Database", () -> {
            Object version = e.queryValue(
                    "SELECT version_full FROM product_component_version WHERE product LIKE 'Oracle Database%'");
            String text = String.valueOf(version);
            if (version == null || !text.contains("21c") && !text.contains("Oracle")) {
                throw new EngineFunctional.HarnessFailure("version_full 异常: " + version);
            }
            return text;
        });

        EngineFunctional.check("oracle.连接落在最小权限验收用户（USER 一致）", () -> {
            Object user = e.queryValue("SELECT USER FROM dual");
            if (!APP_USER.equalsIgnoreCase(String.valueOf(user))) {
                throw new EngineFunctional.HarnessFailure(
                        "USER 期望 " + APP_USER + "，实际 " + user);
            }
            return String.valueOf(user);
        });

        EngineFunctional.check("oracle.VARCHAR2 Unicode 往返（中文 + emoji + 制表符）", () -> {
            execIgnore(e, "DROP TABLE t_acc_utf");
            e.executeSql("CREATE TABLE t_acc_utf (id NUMBER(10) PRIMARY KEY, "
                    + "name VARCHAR2(64 CHAR), note VARCHAR2(64 CHAR))");
            String name = "张三";
            String note = "中文/emoji \uD83D\uDE00/制表\t结束";
            e.executeSql("INSERT INTO t_acc_utf (id, name, note) VALUES (?, ?, ?)", 1, name, note);
            List<Map<String, Object>> rows =
                    e.querySql("SELECT name, note FROM t_acc_utf WHERE id = ?", 1);
            if (rows == null || rows.size() != 1) {
                throw new EngineFunctional.HarnessFailure("读回行数异常: "
                        + (rows == null ? "null" : rows.size()));
            }
            Map<String, Object> row = rows.get(0);
            Object gotName = valueIgnoreCase(row, "name");
            Object gotNote = valueIgnoreCase(row, "note");
            if (!name.equals(gotName)) {
                throw new EngineFunctional.HarnessFailure("name 往返不一致: " + gotName);
            }
            if (!note.equals(gotNote)) {
                throw new EngineFunctional.HarnessFailure("note 往返不一致: " + gotNote);
            }
            // Oracle 的 LENGTH 按字符计数（AL32UTF8 下中文 1 字符 = 1）
            Object len = e.queryValue("SELECT LENGTH('中文') FROM dual");
            if (!(len instanceof Number num) || num.intValue() != 2) {
                throw new EngineFunctional.HarnessFailure("LENGTH('中文') 期望 2，实际 " + len);
            }
            return "round-trip ok, len=" + note.length() + " LENGTH(中文)=" + len;
        });

        EngineFunctional.check("oracle.空串即 NULL（Oracle 专有语义，桩无法伪造）", () -> {
            execIgnore(e, "DROP TABLE t_acc_empty");
            e.executeSql("CREATE TABLE t_acc_empty (id NUMBER(10) PRIMARY KEY, note VARCHAR2(32))");
            e.executeSql("INSERT INTO t_acc_empty (id, note) VALUES (?, ?)", 1, "");
            Object note = e.queryValue("SELECT note FROM t_acc_empty WHERE id = 1");
            if (note != null) {
                throw new EngineFunctional.HarnessFailure("空串应读回 NULL，实际 " + note);
            }
            Object nvl = e.queryValue("SELECT NVL('', 'null') FROM dual");
            if (!"null".equals(nvl)) {
                throw new EngineFunctional.HarnessFailure("NVL('', 'null') 期望 null，实际 " + nvl);
            }
            long nulls = e.count("SELECT COUNT(*) FROM t_acc_empty WHERE note IS NULL");
            if (nulls != 1) {
                throw new EngineFunctional.HarnessFailure("IS NULL 计数期望 1，实际 " + nulls);
            }
            return "'' -> NULL, IS NULL count=" + nulls;
        });

        EngineFunctional.check("oracle.IDENTITY + TIMESTAMP 默认值真实生效", () -> {
            execIgnore(e, "DROP TABLE t_acc_ts");
            e.executeSql("CREATE TABLE t_acc_ts (id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "ts TIMESTAMP NOT NULL DEFAULT SYSTIMESTAMP)");
            e.executeSql("INSERT INTO t_acc_ts (ts) VALUES (DEFAULT)");
            long n = e.count("SELECT COUNT(*) FROM t_acc_ts");
            if (n != 1) {
                throw new EngineFunctional.HarnessFailure("插入后行数期望 1，实际 " + n);
            }
            Object id = e.queryValue("SELECT id FROM t_acc_ts");
            if (!(id instanceof Number num) || num.longValue() != 1L) {
                throw new EngineFunctional.HarnessFailure("IDENTITY 首个值期望 1，实际 " + id);
            }
            Object ts = e.queryValue("SELECT ts FROM t_acc_ts");
            if (ts == null) {
                throw new EngineFunctional.HarnessFailure("TIMESTAMP 默认为 null");
            }
            return "id=" + id + " ts=" + ts.getClass().getSimpleName();
        });

        EngineFunctional.check("oracle.queryPage 真实边界（ROWNUM 模板）：第2页=(3,4)，末页只剩1行", () -> {
            execIgnore(e, "DROP TABLE t_acc_page");
            e.executeSql("CREATE TABLE t_acc_page (id NUMBER(10) PRIMARY KEY, name VARCHAR2(32))");
            for (int i = 1; i <= 5; i++) {
                e.executeSql("INSERT INTO t_acc_page (id, name) VALUES (?, ?)", i, "n" + i);
            }
            List<Map<String, Object>> p2 =
                    e.queryPage("SELECT id, name FROM t_acc_page ORDER BY id", 2, 2);
            assertIds(p2, "第2页", 3L, 4L);
            List<Map<String, Object>> p3 =
                    e.queryPage("SELECT id, name FROM t_acc_page ORDER BY id", 3, 2);
            assertIds(p3, "第3页", 5L);
            List<Map<String, Object>> p9 =
                    e.queryPage("SELECT id, name FROM t_acc_page ORDER BY id", 9, 2);
            if (p9 == null || !p9.isEmpty()) {
                throw new EngineFunctional.HarnessFailure("越界页应为空");
            }
            return "p2=3,4 p3=5 p9=empty";
        });

        EngineFunctional.check("oracle.Oracle 专有 SQL 真实可用（DATE 算术 / DECODE / ROWNUM）", () -> {
            Object nextDay = e.queryValue(
                    "SELECT TO_CHAR(DATE '2020-01-02' + 1, 'YYYY-MM-DD') FROM dual");
            if (!"2020-01-03".equals(nextDay)) {
                throw new EngineFunctional.HarnessFailure("DATE 算术异常: " + nextDay);
            }
            Object decoded = e.queryValue("SELECT DECODE(2, 1, 'one', 2, 'two', 'other') FROM dual");
            if (!"two".equals(decoded)) {
                throw new EngineFunctional.HarnessFailure("DECODE 异常: " + decoded);
            }
            List<Map<String, Object>> top = e.querySql(
                    "SELECT id FROM (SELECT id FROM t_acc_page ORDER BY id) WHERE ROWNUM <= 2 ORDER BY id");
            if (top == null || top.size() != 2) {
                throw new EngineFunctional.HarnessFailure("ROWNUM 截断期望 2 行，实际 "
                        + (top == null ? "null" : top.size()));
            }
            assertIds(top, "ROWNUM 前两行", 1L, 2L);
            return "date=" + nextDay + " decode=" + decoded + " rownumRows=2";
        });

        EngineFunctional.check("oracle.查询不存在的表：异常带服务端原因（ORA-00942）", () -> {
            try {
                e.querySql("SELECT * FROM t_acc_no_such_table");
                throw new EngineFunctional.HarnessFailure("未抛异常");
            } catch (EngineFunctional.HarnessFailure f) {
                throw f;
            } catch (Exception expected) {
                String msg = String.valueOf(expected.getMessage());
                if (!msg.toUpperCase().contains("T_ACC_NO_SUCH_TABLE")) {
                    throw new EngineFunctional.HarnessFailure(
                            "异常消息未带表名: " + expected.getMessage());
                }
                if (!msg.contains("ORA-00942") && !msg.toUpperCase().contains("DOES NOT EXIST")
                        && !msg.contains("不存在")) {
                    throw new EngineFunctional.HarnessFailure(
                            "异常消息未带服务端原因: " + expected.getMessage());
                }
                return "SQLState=" + sqlState(expected);
            }
        });

        EngineFunctional.check("oracle.主键冲突：写失败且不留半条数据（ORA-00001）", () -> {
            long before = e.count("SELECT COUNT(*) FROM t_acc_utf");
            try {
                e.executeSql("INSERT INTO t_acc_utf (id, name, note) VALUES (?, ?, ?)",
                        1, "重复", "重复");
                throw new EngineFunctional.HarnessFailure("主键冲突未抛异常");
            } catch (EngineFunctional.HarnessFailure f) {
                throw f;
            } catch (Exception expected) {
                long after = e.count("SELECT COUNT(*) FROM t_acc_utf");
                if (after != before) {
                    throw new EngineFunctional.HarnessFailure(
                            "失败写入改变了行数: " + before + " -> " + after);
                }
                String msg = String.valueOf(expected.getMessage());
                if (!msg.contains("ORA-00001") && !msg.toUpperCase().contains("UNIQUE")) {
                    throw new EngineFunctional.HarnessFailure(
                            "异常消息未带约束原因: " + expected.getMessage());
                }
                return "SQLState=" + sqlState(expected) + " rows=" + after;
            }
        });

        EngineFunctional.check("oracle.引擎方言与真实分页一致：supportsLimit=false + ROWNUM 模板", () -> {
            var dialect = ((com.chua.datasource.support.engine.AbstractEngine) e).getDialect();
            if (dialect == null || !"oracle".equals(dialect.protocol())) {
                throw new EngineFunctional.HarnessFailure("方言协议异常: "
                        + (dialect == null ? null : dialect.protocol()));
            }
            if (dialect.supportsLimit()) {
                throw new EngineFunctional.HarnessFailure("oracle 不应声称支持 LIMIT");
            }
            String sql = dialect.processSql("SELECT id FROM t_acc_page ORDER BY id",
                    new com.chua.common.support.lang.datasource.dialect.Pagination()
                            .setPageNum(2).setPageSize(3));
            String upper = sql.toUpperCase();
            if (!upper.contains("ROWNUM ROW_ID") || !upper.contains("ROW_ID > 3")) {
                throw new EngineFunctional.HarnessFailure("分页 SQL 异常: " + sql);
            }
            return sql;
        });

        cleanup(e);
    }

    // ==================== 辅助 ====================

    private static String env(String key, String fallback) {
        String value = System.getenv(key);
        if (value == null || value.isBlank()) {
            value = System.getProperty(key);
        }
        return value == null || value.isBlank() ? fallback : value;
    }

    /** Oracle 没有 DROP TABLE IF EXISTS，用 PL/SQL 吞掉 ORA-00942。 */
    private static void execIgnore(Engine e, String ddl) {
        try {
            e.executeSql("BEGIN EXECUTE IMMEDIATE '" + ddl.replace("'", "''")
                    + "'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -942 THEN RAISE; END IF; END;");
        } catch (RuntimeException ignored) {
            // 清理失败不影响断言结论
        }
    }

    private static void dropAll(Engine e) {
        for (String table : new String[]{"t_acc_user", "t_acc_utf", "t_acc_ts",
                "t_acc_page", "t_acc_empty"}) {
            execIgnore(e, "DROP TABLE " + table);
        }
    }

    private static void cleanup(Engine e) {
        dropAll(e);
    }

    private static void assertIds(List<Map<String, Object>> rows, String page, Long... expected) {
        if (rows == null || rows.size() != expected.length) {
            throw new EngineFunctional.HarnessFailure(page + " 行数期望 " + expected.length
                    + "，实际 " + (rows == null ? "null" : rows.size()));
        }
        for (int i = 0; i < expected.length; i++) {
            Object got = valueIgnoreCase(rows.get(i), "id");
            if (!(got instanceof Number num) || num.longValue() != expected[i]) {
                throw new EngineFunctional.HarnessFailure(
                        page + " 第" + (i + 1) + "行 id 期望 " + expected[i] + "，实际 " + got);
            }
        }
    }

    private static Object valueIgnoreCase(Map<String, Object> row, String column) {
        if (row == null) {
            return null;
        }
        for (Map.Entry<String, Object> entry : row.entrySet()) {
            if (column.equalsIgnoreCase(entry.getKey())) {
                return entry.getValue();
            }
        }
        return null;
    }

    private static String sqlState(Throwable t) {
        Throwable cur = t;
        while (cur != null) {
            if (cur instanceof java.sql.SQLException sql) {
                return sql.getSQLState();
            }
            cur = cur.getCause();
        }
        return "n/a";
    }

    private static boolean reachable() {
        try (Socket socket = new Socket()) {
            socket.connect(new InetSocketAddress(HOST, PORT), 2000);
            return true;
        } catch (Exception e) {
            return false;
        }
    }
}
