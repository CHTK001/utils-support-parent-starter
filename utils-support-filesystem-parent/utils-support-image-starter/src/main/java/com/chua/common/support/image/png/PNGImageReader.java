    @Override
    /**
      * 获取镜像类型
     * @param imageIndex 镜像索引
     */
    public Iterator<ImageTypeSpecifier> getImageTypes(int imageIndex)
      throws IIOException
    {

        readMetadata();

        if (!isAnimated && imageIndex != 0) {
            throw new IndexOutOfBoundsException("imageIndex != 0!");
        }

        ArrayList<ImageTypeSpecifier> l =
            new ArrayList<ImageTypeSpecifier>(1);

        ColorSpace rgb;
        ColorSpace gray;
        int[] bandOffsets;

        int bitDepth = metadata.IHDR_bitDepth;
        int colorType = metadata.IHDR_colorType;

        int dataType;
        if (bitDepth <= 8) {
            dataType = DataBuffer.TYPE_BYTE;
        } else {
            dataType = DataBuffer.TYPE_USHORT;
        }

        switch (colorType) {
        /*
          * For PNG 镜像 的 color 类型 PNG_COLOR_RGB 或 PNG_COLOR_GRAY that
          * contain a 特定 transparent color (given by trns chunk), we 添加
          * 镜像类型specifier(s) that 支持 transparency 转为 the 列表 的
          * 支持 镜像 类型.
         */
        case PNG_COLOR_GRAY:
 // Need trns chunk
            readMetadata();

            if (metadata.hasTransparentColor()) {
                gray = ColorSpace.getInstance(ColorSpace.CS_GRAY);
                bandOffsets = new int[2];
                bandOffsets[0] = 0;
                bandOffsets[1] = 1;
                l.add(ImageTypeSpecifier.createInterleaved(gray,
                                                           bandOffsets,
                                                           dataType,
                                                           true,
                                                           false));
            }
            // Packed grayscale
            l.add(ImageTypeSpecifier.createGrayscale(bitDepth,
                                                     dataType,
                                                     false));
            break;

        case PNG_COLOR_RGB:
 // Need trns chunk
            readMetadata();

            if (bitDepth == 8) {
                if (metadata.hasTransparentColor()) {
                    l.add(ImageTypeSpecifier.createFromBufferedImageType(
                            BufferedImage.TYPE_4BYTE_ABGR));
                }
 // some 标准 类型 的 缓冲 镜像
 // which 能否 be used as 目标
                l.add(ImageTypeSpecifier.createFromBufferedImageType(
                          BufferedImage.TYPE_3BYTE_BGR));

                l.add(ImageTypeSpecifier.createFromBufferedImageType(
                          BufferedImage.TYPE_INT_RGB));

                l.add(ImageTypeSpecifier.createFromBufferedImageType(
                          BufferedImage.TYPE_INT_BGR));

            }

            if (metadata.hasTransparentColor()) {
                rgb = ColorSpace.getInstance(ColorSpace.CS_sRGB);
                bandOffsets = new int[4];
                bandOffsets[0] = 0;
                bandOffsets[1] = 1;
                bandOffsets[2] = 2;
                bandOffsets[3] = 3;

                l.add(ImageTypeSpecifier.
                    createInterleaved(rgb, bandOffsets,
                                      dataType, true, false));
            }
 // 组件 R, G, B
            rgb = ColorSpace.getInstance(ColorSpace.CS_sRGB);
            bandOffsets = new int[3];
            bandOffsets[0] = 0;
            bandOffsets[1] = 1;
            bandOffsets[2] = 2;
            l.add(ImageTypeSpecifier.createInterleaved(rgb,
                                                       bandOffsets,
                                                       dataType,
                                                       false,
                                                       false));
            break;

        case PNG_COLOR_PALETTE:
 // Need trns chunk
            readMetadata();

            /*
             * The PLTE chunk spec says:
             *
              * The 数字 的 palette entries must not exceed the 范围 that
              * 能否 be represented 入 the 镜像 钻头 深度 (for example, 2^4 = 16
              * for a 钻头 深度 的 4). It 是否 permissible 转为 have fewer entries
              * than the 钻头 深度 would allow. 入 that 大小写, 任意 出-的-范围
              * pixel 值 found 入 the 镜像 数据 是否 an 错误.
             *
             * http://www.libpng.org/pub/png/spec/1.2/PNG-Chunks.html#C.PLTE
             *
              * Consequently, the 大小写 When.js the palette 长度 是否 smaller than
              * 2^钻头深度 是否 legal 入 the view 的 PNG spec.
             *
              * However the spec 的 创建索引() 方法 demands the exact
              * equality 的 the palette lengh 和 数字 的 possible palette
              * entries (2^钻头深度).
             *
             * {@link javax.imageio.ImageTypeSpecifier.html#createIndexed}
             *
              * 入 订单 转为 avoid this contradiction we need 转为 extend the
              * palette arrays 转为 the 限制 defined by the 钻头深度.
             */

            int plength = 1 << bitDepth;

            byte[] red = metadata.PLTE_red;
            byte[] green = metadata.PLTE_green;
            byte[] blue = metadata.PLTE_blue;

            if (metadata.PLTE_red.length < plength) {
                red = Arrays.copyOf(metadata.PLTE_red, plength);
                Arrays.fill(red, metadata.PLTE_red.length, plength,
                            metadata.PLTE_red[metadata.PLTE_red.length - 1]);

                green = Arrays.copyOf(metadata.PLTE_green, plength);
                Arrays.fill(green, metadata.PLTE_green.length, plength,
                            metadata.PLTE_green[metadata.PLTE_green.length - 1]);

                blue = Arrays.copyOf(metadata.PLTE_blue, plength);
                Arrays.fill(blue, metadata.PLTE_blue.length, plength,
                            metadata.PLTE_blue[metadata.PLTE_blue.length - 1]);

            }

 // Alpha 从 trns chunk may have fewer entries than
 // the RGB luts 从 the PLTE chunk; if so, pad with
            // 255.
            byte[] alpha = null;
            if (metadata.tRNS_present && (metadata.tRNS_alpha != null)) {
                if (metadata.tRNS_alpha.length == red.length) {
                    alpha = metadata.tRNS_alpha;
                } else {
                    alpha = Arrays.copyOf(metadata.tRNS_alpha, red.length);
                    Arrays.fill(alpha,
                                metadata.tRNS_alpha.length,
                                red.length, (byte)255);
                }
            }

            l.add(ImageTypeSpecifier.createIndexed(red, green,
                                                   blue, alpha,
                                                   bitDepth,
                                                   DataBuffer.TYPE_BYTE));
            break;

        case PNG_COLOR_GRAY_ALPHA:
 // 组件 G, A
            gray = ColorSpace.getInstance(ColorSpace.CS_GRAY);
            bandOffsets = new int[2];
            bandOffsets[0] = 0;
            bandOffsets[1] = 1;
            l.add(ImageTypeSpecifier.createInterleaved(gray,
                                                       bandOffsets,
                                                       dataType,
                                                       true,
                                                       false));
            break;

        case PNG_COLOR_RGB_ALPHA:
            if (bitDepth == 8) {
 // some 标准 类型 的 缓冲 镜像
 // wich 能否 be used as 目标
                l.add(ImageTypeSpecifier.createFromBufferedImageType(
                          BufferedImage.TYPE_4BYTE_ABGR));

                l.add(ImageTypeSpecifier.createFromBufferedImageType(
                          BufferedImage.TYPE_INT_ARGB));
            }

            // Component R, G, B, A (non-premultiplied)
            rgb = ColorSpace.getInstance(ColorSpace.CS_sRGB);
            bandOffsets = new int[4];
            bandOffsets[0] = 0;
            bandOffsets[1] = 1;
            bandOffsets[2] = 2;
            bandOffsets[3] = 3;

            l.add(ImageTypeSpecifier.createInterleaved(rgb,
                                                       bandOffsets,
                                                       dataType,
                                                       true,
                                                       false));
            break;

        default:
            break;
        }

        return l.iterator();
    }

    /*
      * 父 类 implementation uses 第一个 element
      * 的 镜像 类型 列表 as raw 镜像 类型.
     *
      * Also, 父 implementation uses 第一个 element 的 this 列表
      * as 默认 目标 类型 镜像 读取 参数 执行 not specify
     * anything other.
     *
      * However, 入 大小写 的 RGB 和 RGBA color 类型, raw 镜像 类型
      * produces 缓冲 镜像 的 习俗 类型. It causes some
      * 表现 degradation 的 subsequent rendering operations.
     *
      * 转为 resolve this contradiction we 放入 标准 镜像 类型
      * at the 第一个 位置 的 镜像 类型 列表 (转为 produce 标准
      * 镜像 by 默认) 和 放入 raw 镜像 类型 (which 是否 习俗)
      * at the 最后一个 位置 的 this 列表.
     *
      * 之后 this 改变 we should override 获取raw镜像类型()
      * 转为 返回 最后一个 element 的 镜像 类型 列表.
     */
    @Override
    public ImageTypeSpecifier getRawImageType(int imageIndex)
      throws IOException {

        Iterator<ImageTypeSpecifier> types = getImageTypes(imageIndex);
        ImageTypeSpecifier raw = null;
        do {
            raw = types.next();
        } while (types.hasNext());
        return raw;
    }

