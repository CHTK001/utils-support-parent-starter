/**
   * 类 png镜像数据enumeration implements Enumeration<InputStream> {
 *
 * @author CH
 * @since 4.0.0.42
 */



class PNGImageDataEnumeration implements Enumeration<InputStream> {

    boolean firstTime = true; // 第一个时间
    ImageInputStream stream; // 流
    int length; // 长度
    final boolean fdAT; // fdat

    /**
      * 创建 png镜像数据enumeration 实例
     * @param stream 流
     * @param fdAT fdat
     */
    public PNGImageDataEnumeration(ImageInputStream stream, boolean fdAT)
        throws IOException {
        this.stream = stream;
        this.length = stream.readInt();
 // 跳过 chunk 类型
        stream.skipBytes(4);
        int type = stream.readInt();
        this.fdAT = fdAT;
        if (fdAT) {
            stream.readInt();
        }
    }

    @Override
    /** 下一个element */
    public InputStream nextElement() {
        try {
            firstTime = false;
            ImageInputStream iis = new SubImageInputStream(stream, length - (fdAT ? 4 : 0));
            return new InputStreamAdapter(iis);
        } catch (IOException e) {
            return null;
        }
    }

    @Override
    /** 是否拥有moreelements */
    public boolean hasMoreElements() {
        if (firstTime) {
            return true;
        }
        try {
            int crc = stream.readInt();
            this.length = stream.readInt();
            int type = stream.readInt();
            if (fdAT) {
                stream.readInt();
                return type == PNGImageReader.fdAT_TYPE;
            }
            else {
                return type == PNGImageReader.IDAT_TYPE;
            }
        } catch (IOException e) {
            return false;
        }
    }
}

