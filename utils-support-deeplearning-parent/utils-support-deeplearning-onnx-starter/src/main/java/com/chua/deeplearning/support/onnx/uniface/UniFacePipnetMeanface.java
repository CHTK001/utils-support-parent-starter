    /**
     * 反向索引 1（长度 NUM_POINTS * maxLen）。
     */
    private final int[] reverseIndex1;

    /**
     * 反向索引 2（长度 NUM_POINTS * maxLen）。
     */
    private final int[] reverseIndex2;

    /**
     * 反向索引最大长度。
     */
    private final int maxLen;

    private UniFacePipnetMeanface() {
        int n = NUM_POINTS;
        int k = NUM_NEIGHBORS;

        // meanface_indices[i] = 距离点 i 最近的 k 个点（不含自身）
        int[][] meanfaceIndices = new int[n][k];
        for (int i = 0; i < n; i++) {
            double[] dists = new double[n];
            for (int j = 0; j < n; j++) {
                double dx = MEANFACE_WFLW_98[2 * i] - MEANFACE_WFLW_98[2 * j];
                double dy = MEANFACE_WFLW_98[2 * i + 1] - MEANFACE_WFLW_98[2 * j + 1];
                dists[j] = dx * dx + dy * dy;
            }
            Integer[] order = new Integer[n];
            for (int j = 0; j < n; j++) {
                order[j] = j;
            }
            Arrays.sort(order, (a, b) -> Double.compare(dists[a], dists[b]));
            for (int j = 0; j < k; j++) {
                meanfaceIndices[i][j] = order[j + 1];
            }
        }

        // reversed_map[i] = (哪些点的邻居里包含 i, i 在对方邻居列表中的下标)
        List<List<Integer>> revFirst = new ArrayList<>(n);
        List<List<Integer>> revSecond = new ArrayList<>(n);
        for (int i = 0; i < n; i++) {
            revFirst.add(new ArrayList<>());
            revSecond.add(new ArrayList<>());
        }
        for (int i = 0; i < n; i++) {
            for (int j = 0; j < k; j++) {
                int neighbor = meanfaceIndices[i][j];
                revFirst.get(neighbor).add(i);
                revSecond.get(neighbor).add(j);
            }
        }

        int max = 0;
        for (int i = 0; i < n; i++) {
            max = Math.max(max, revFirst.get(i).size());
        }
        this.maxLen = max;

        this.reverseIndex1 = new int[n * max];
        this.reverseIndex2 = new int[n * max];
        for (int i = 0; i < n; i++) {
            List<Integer> idx1 = revFirst.get(i);
            List<Integer> idx2 = revSecond.get(i);
            int need = max - idx1.size();
            // Python 列表重复语义：idx * max_len 取前 need 个（整表循环复制）
            for (int j = 0; j < idx1.size(); j++) {
                reverseIndex1[i * max + j] = idx1.get(j);
                reverseIndex2[i * max + j] = idx2.get(j);
            }
            for (int j = 0; j < need; j++) {
                reverseIndex1[i * max + idx1.size() + j] = idx1.get(j % idx1.size());
                reverseIndex2[i * max + idx2.size() + j] = idx2.get(j % idx2.size());
            }
        }
    }

